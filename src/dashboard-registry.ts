/** Resolve a stored widget type through consolidation aliases; returns null when unknown. */
export function resolveDashboardWidgetType(type: unknown): DashboardWidgetType | null {
  if (typeof type !== 'string') return null;
  const aliased: DashboardWidgetType | undefined = DASHBOARD_WIDGET_TYPE_ALIASES[type];
  if (aliased) return aliased;
  return KNOWN_DASHBOARD_WIDGET_TYPES.has(type as DashboardWidgetType) ? (type as DashboardWidgetType) : null;
}
